; MF with r nonzero and n zero: the exponent sum uses n's exponent field,
; and I_FP_OF / I_FP_UF fire when it is out of range. The result is still
; all-zero words with Z set. With r zero there is no interrupt.

	.include awp-fp.inc

operation:
	lf	r7+ARG1
	mf	r7+ARG2
	uj	r5

tests:
	; 64 + 64 = 128
	.word	0, ?Z, I_FP_OF
	.word	0x4000, 0x0000, 0x0040
	.word	0x0000, 0x0000, 0x0040
	.word	0x0000, 0x0000, 0x0000

	; 1 + 127 = 128
	.word	0, ?Z, I_FP_OF
	.word	0x8000, 0x0000, 0x0001
	.word	0x0000, 0x0000, 0x007f
	.word	0x0000, 0x0000, 0x0000

	; 127 + 0 = 127
	.word	0, ?Z, 0
	.word	0x4000, 0x0000, 0x007f
	.word	0x0000, 0x0000, 0x0000
	.word	0x0000, 0x0000, 0x0000

	; -64 + -64 = -128
	.word	0, ?Z, 0
	.word	0x4000, 0x0000, 0x00c0
	.word	0x0000, 0x0000, 0x00c0
	.word	0x0000, 0x0000, 0x0000

	; -64 + -65 = -129
	.word	0, ?Z, I_FP_UF
	.word	0x4000, 0x0000, 0x00c0
	.word	0x0000, 0x0000, 0x00bf
	.word	0x0000, 0x0000, 0x0000

	; -128 + -1 = -129
	.word	0, ?Z, I_FP_UF
	.word	0x4000, 0x0000, 0x0080
	.word	0x0000, 0x0000, 0x00ff
	.word	0x0000, 0x0000, 0x0000

	; 127 + 72 = 199, V kept
	.word	?V, ?Z|?V, I_FP_OF
	.word	0x87ff, 0xfe00, 0x007f
	.word	0x0000, 0x0000, 0x0048
	.word	0x0000, 0x0000, 0x0000

	; -44 + -110 = -154
	.word	0, ?Z, I_FP_UF
	.word	0x5280, 0x0000, 0x00d4
	.word	0x0000, 0x0000, 0x0092
	.word	0x0000, 0x0000, 0x0000

	; r zero: 118 + 19 = 137, no interrupt
	.word	?V, ?Z|?V, 0
	.word	0x0000, 0x0000, 0x0076
	.word	0x8000, 0x0000, 0x0013
	.word	0x0000, 0x0000, 0x0000

	; both zero: 120 + 118 = 238, no interrupt
	.word	0, ?Z, 0
	.word	0x0000, 0x0000, 0x0078
	.word	0x0000, 0x0000, 0x0076
	.word	0x0000, 0x0000, 0x0000
fin:
